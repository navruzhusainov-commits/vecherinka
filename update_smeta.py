def item(name, price, discount, qty=1, days=1, jur="ООО \"МРИЯ\"", note=""):
    """Строка в формате исходной сметы: C=цена, D=скидка, E=C-(C*D), F=кол-во, G=дн, H=C*F*G, I=E*F*G."""
    global r
    cell(f"B{r}", name, align=LEFT)
    cell(f"C{r}", price, num=True, align=CENTER)
    cell(f"D{r}", discount, num=True, align=CENTER)
    cell(f"E{r}", f"=C{r}-(C{r}*D{r})", num=True, align=CENTER)
    cell(f"F{r}", qty, num=True, align=CENTER)
    cell(f"G{r}", days, num=True, align=CENTER)
    cell(f"H{r}", f"=C{r}*F{r}*G{r}", num=True, align=CENTER)
    cell(f"I{r}", f"=E{r}*F{r}*G{r}", num=True, align=CENTER)
    cell(f"J{r}", jur, align=CENTER)
    if note:
        cell(f"K{r}", note, size=11, italic=True, align=LEFT)
    r += 1
    return r - 1

